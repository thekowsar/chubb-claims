-- V1: full schema from planning/03-db-design.md (sections 3 and 4).
-- Hibernate runs with ddl-auto=validate, so this file is the only owner of the schema.

-- 3.0 roles
CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL,
    name        VARCHAR(50)  NOT NULL,
    description VARCHAR(200),
    CONSTRAINT uk_roles_code UNIQUE (code)
);

-- 3.1 users
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role_id       BIGINT       NOT NULL,
    enabled       BOOLEAN      DEFAULT TRUE NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

-- 3.2 claims
CREATE SEQUENCE claim_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE claims (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_number      VARCHAR(20)   NOT NULL,
    type              VARCHAR(10)   NOT NULL,
    market            VARCHAR(2)    NOT NULL,
    policy_number     VARCHAR(30)   NOT NULL,
    incident_date     DATE          NOT NULL,
    location          VARCHAR(200)  NOT NULL,
    description       VARCHAR(2000) NOT NULL,
    estimated_amount  DECIMAL(15,2) NOT NULL,
    currency          VARCHAR(3)    NOT NULL,
    status            VARCHAR(15)   NOT NULL,
    claimant_id       BIGINT        NOT NULL,
    assigned_staff_id BIGINT,
    assessed_amount   DECIMAL(15,2),
    settled_amount    DECIMAL(15,2),
    decision_note     VARCHAR(2000),
    assigned_at       TIMESTAMP WITH TIME ZONE,
    started_at        TIMESTAMP WITH TIME ZONE,
    closed_at         TIMESTAMP WITH TIME ZONE,
    version           BIGINT        DEFAULT 0 NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by        VARCHAR(50)   NOT NULL,
    updated_by        VARCHAR(50)   NOT NULL,
    CONSTRAINT uk_claims_claim_number UNIQUE (claim_number),
    CONSTRAINT fk_claims_claimant FOREIGN KEY (claimant_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_claims_staff FOREIGN KEY (assigned_staff_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_claims_type CHECK (type IN ('MOTOR', 'PROPERTY')),
    CONSTRAINT ck_claims_market CHECK (market IN ('SG', 'HK', 'AU', 'MY', 'TH', 'ID')),
    CONSTRAINT ck_claims_currency CHECK (currency IN ('SGD', 'HKD', 'AUD', 'MYR', 'THB', 'IDR')),
    CONSTRAINT ck_claims_status CHECK (status IN ('SUBMITTED', 'ASSIGNED', 'IN_PROGRESS', 'SETTLED', 'REJECTED')),
    CONSTRAINT ck_claims_estimated_positive CHECK (estimated_amount > 0),
    CONSTRAINT ck_claims_assessed_non_negative CHECK (assessed_amount IS NULL OR assessed_amount >= 0),
    CONSTRAINT ck_claims_settled_positive CHECK (settled_amount IS NULL OR settled_amount > 0),
    CONSTRAINT ck_claims_assignee_required CHECK (status = 'SUBMITTED' OR assigned_staff_id IS NOT NULL),
    CONSTRAINT ck_claims_settled_fields CHECK (status <> 'SETTLED' OR (assessed_amount IS NOT NULL AND settled_amount IS NOT NULL AND decision_note IS NOT NULL AND closed_at IS NOT NULL)),
    CONSTRAINT ck_claims_rejected_fields CHECK (status <> 'REJECTED' OR (decision_note IS NOT NULL AND closed_at IS NOT NULL)),
    CONSTRAINT ck_claims_settled_le_assessed CHECK (settled_amount IS NULL OR settled_amount <= assessed_amount)
);

-- 3.3 claim_messages
CREATE TABLE claim_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id   BIGINT        NOT NULL,
    author_id  BIGINT        NOT NULL,
    body       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(50)   NOT NULL,
    CONSTRAINT fk_messages_claim FOREIGN KEY (claim_id) REFERENCES claims (id) ON DELETE RESTRICT,
    CONSTRAINT fk_messages_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE RESTRICT
);

-- 3.4 claim_status_history
CREATE TABLE claim_status_history (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id          BIGINT      NOT NULL,
    from_status       VARCHAR(15),
    to_status         VARCHAR(15) NOT NULL,
    changed_by        BIGINT      NOT NULL,
    assigned_staff_id BIGINT,
    changed_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_history_claim FOREIGN KEY (claim_id) REFERENCES claims (id) ON DELETE RESTRICT,
    CONSTRAINT fk_history_user FOREIGN KEY (changed_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_history_from_status CHECK (from_status IS NULL OR from_status IN ('SUBMITTED', 'ASSIGNED', 'IN_PROGRESS', 'SETTLED', 'REJECTED')),
    CONSTRAINT ck_history_to_status CHECK (to_status IN ('SUBMITTED', 'ASSIGNED', 'IN_PROGRESS', 'SETTLED', 'REJECTED'))
);

-- 3.5 menus and role_menu
CREATE TABLE menus (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL,
    label      VARCHAR(50)  NOT NULL,
    route      VARCHAR(100) NOT NULL,
    icon       VARCHAR(30),
    sort_order INT          NOT NULL,
    enabled    BOOLEAN      DEFAULT TRUE NOT NULL,
    CONSTRAINT uk_menus_code UNIQUE (code)
);

CREATE TABLE role_menu (
    role_id BIGINT NOT NULL,
    menu_id BIGINT NOT NULL,
    CONSTRAINT pk_role_menu PRIMARY KEY (role_id, menu_id),
    CONSTRAINT fk_role_menu_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT,
    CONSTRAINT fk_role_menu_menu FOREIGN KEY (menu_id) REFERENCES menus (id) ON DELETE RESTRICT
);

-- 4.3 indexes
CREATE INDEX ix_users_role ON users (role_id);
CREATE INDEX ix_claims_claimant_created ON claims (claimant_id, created_at DESC);
CREATE INDEX ix_claims_staff_status ON claims (assigned_staff_id, status);
CREATE INDEX ix_claims_status_created ON claims (status, created_at DESC);
CREATE INDEX ix_claims_market_currency_status ON claims (market, currency, status);
CREATE INDEX ix_claims_type ON claims (type);
CREATE INDEX ix_messages_claim_created ON claim_messages (claim_id, created_at);
CREATE INDEX ix_history_claim_changed ON claim_status_history (claim_id, changed_at);
